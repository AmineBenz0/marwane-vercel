SET LOCAL lock_timeout = '5s';
ALTER TABLE public.transactions ADD COLUMN IF NOT EXISTS allocation_automatique boolean NOT NULL DEFAULT false;
ALTER TABLE public.transactions ADD COLUMN IF NOT EXISTS est_promesse boolean NOT NULL DEFAULT false;
ALTER TABLE public.transactions ADD COLUMN IF NOT EXISTS date_livraison_prevue date;
CREATE TABLE public.egg_sale_allocations (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_transaction integer NOT NULL REFERENCES public.transactions(id_transaction) ON DELETE CASCADE,
 id_production integer NOT NULL REFERENCES public.productions(id_production) ON DELETE RESTRICT,
 quantite integer NOT NULL,
 CONSTRAINT egg_allocation_positive CHECK (quantite > 0),
 CONSTRAINT egg_allocation_source_unique UNIQUE(id_transaction,id_production)
);
CREATE INDEX ix_egg_sale_allocations_id_transaction ON public.egg_sale_allocations(id_transaction);
CREATE INDEX ix_egg_sale_allocations_id_production ON public.egg_sale_allocations(id_production);
CREATE INDEX IF NOT EXISTS ix_transactions_date_livraison_prevue ON public.transactions(date_livraison_prevue);
INSERT INTO public.egg_sale_allocations(id_transaction,id_production,quantite)
 SELECT id_transaction,id_production,quantite FROM public.transactions WHERE id_production IS NOT NULL;
ALTER TABLE public.egg_sale_allocations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.egg_sale_allocations FROM PUBLIC,anon,authenticated;
REVOKE ALL ON SEQUENCE public.egg_sale_allocations_id_seq FROM PUBLIC,anon,authenticated;
CREATE POLICY runtime_allocation_access ON public.egg_sale_allocations TO app_runtime USING (true) WITH CHECK (true);
GRANT SELECT,INSERT,UPDATE,DELETE ON public.egg_sale_allocations TO app_runtime;
GRANT USAGE,SELECT ON SEQUENCE public.egg_sale_allocations_id_seq TO app_runtime;
