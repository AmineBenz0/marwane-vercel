-- Convert shared parent lots into one parent per building cycle.
-- Keep an immutable mapping so the rollout can be reconciled and replayed.
BEGIN;
SET LOCAL lock_timeout = '10s';
SET LOCAL statement_timeout = '120s';
LOCK TABLE public.lots_production, public.cycles_production IN SHARE ROW EXCLUSIVE MODE;

CREATE TABLE IF NOT EXISTS public.independent_lot_migration_map (
    migration_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    old_lot_id INTEGER,
    id_cycle INTEGER,
    new_lot_id INTEGER,
    action VARCHAR(40) NOT NULL,
    reconciliation_status VARCHAR(30) NOT NULL,
    reconciliation_reason TEXT,
    parent_snapshot_before JSONB,
    cycle_snapshot_before JSONB,
    migrated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_independent_lot_map_shape CHECK (
        (action = 'empty_parent_archived' AND old_lot_id IS NOT NULL
            AND id_cycle IS NULL AND new_lot_id IS NULL)
        OR
        (action <> 'empty_parent_archived' AND id_cycle IS NOT NULL
            AND new_lot_id IS NOT NULL)
    )
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_independent_lot_map_cycle
    ON public.independent_lot_migration_map (id_cycle) WHERE id_cycle IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_independent_lot_map_empty_parent
    ON public.independent_lot_migration_map (old_lot_id)
    WHERE action = 'empty_parent_archived';
CREATE UNIQUE INDEX IF NOT EXISTS uq_independent_lot_map_new_lot
    ON public.independent_lot_migration_map (new_lot_id) WHERE new_lot_id IS NOT NULL;

-- Fail on values that cannot be migrated without guessing. Flock size may be
-- unknown; that NULL is retained and reported instead of filled from a total.
DO $preflight$
DECLARE duplicate_building INTEGER;
BEGIN
    SELECT id_batiment INTO duplicate_building
    FROM public.cycles_production
    WHERE statut IN ('actif', 'a_cloturer')
    GROUP BY id_batiment HAVING count(*) > 1
    ORDER BY id_batiment LIMIT 1;
    IF FOUND THEN
        RAISE EXCEPTION 'Independent-lot migration blocked: building % has overlapping active cycles.',
            duplicate_building;
    END IF;
END
$preflight$;

-- Snapshot all sources before reusing any existing parent row. This makes the
-- archive deterministic even when the first child keeps the old primary key.
CREATE TEMP TABLE independent_lot_migration_source ON COMMIT DROP AS
SELECT
    c.id_cycle,
    c.id_lot AS old_lot_id,
    c.id_batiment,
    c.nom_cycle,
    c.souche AS cycle_souche,
    c.date_debut AS cycle_date_debut,
    c.age_depart_semaines AS cycle_age_depart_semaines,
    c.effectif_initial AS cycle_effectif_initial,
    c.duree_semaines AS cycle_duree_semaines,
    c.date_fin_prevue AS cycle_date_fin_prevue,
    c.date_fin_reelle AS cycle_date_fin_reelle,
    c.statut AS cycle_statut,
    c.notes AS cycle_notes,
    c.date_creation AS cycle_date_creation,
    c.date_modification AS cycle_date_modification,
    c.id_utilisateur_creation AS cycle_user_creation,
    c.id_utilisateur_modification AS cycle_user_modification,
    l.id_lot AS parent_id,
    l.nom_lot AS parent_nom_lot,
    l.souche AS parent_souche,
    l.date_debut AS parent_date_debut,
    l.age_depart_semaines AS parent_age_depart_semaines,
    l.effectif_initial AS parent_effectif_initial,
    l.duree_semaines AS parent_duree_semaines,
    l.date_fin_prevue AS parent_date_fin_prevue,
    l.date_fin_reelle AS parent_date_fin_reelle,
    l.statut AS parent_statut,
    l.notes AS parent_notes,
    l.date_creation AS parent_date_creation,
    l.date_modification AS parent_date_modification,
    l.id_utilisateur_creation AS parent_user_creation,
    l.id_utilisateur_modification AS parent_user_modification,
    to_jsonb(l) AS parent_snapshot,
    to_jsonb(c) AS cycle_snapshot,
    count(*) OVER (PARTITION BY CASE
        WHEN l.id_lot IS NULL THEN c.id_cycle ELSE l.id_lot END)::INTEGER AS child_count,
    row_number() OVER (PARTITION BY CASE
        WHEN l.id_lot IS NULL THEN c.id_cycle ELSE l.id_lot END
        ORDER BY c.id_cycle)::INTEGER AS child_ordinal,
    sum(c.effectif_initial) OVER (PARTITION BY CASE
        WHEN l.id_lot IS NULL THEN c.id_cycle ELSE l.id_lot END) AS child_flock_total,
    bool_and(c.effectif_initial IS NOT NULL) OVER (PARTITION BY CASE
        WHEN l.id_lot IS NULL THEN c.id_cycle ELSE l.id_lot END) AS all_child_flocks_known
FROM public.cycles_production c
LEFT JOIN public.lots_production l ON l.id_lot = c.id_lot;

-- Empty parents have no cycle from which a building could be inferred. Archive
-- their full row and remove them from the operational lots table; they remain
-- visible in the mapping table for manual reconciliation.
INSERT INTO public.independent_lot_migration_map (
    old_lot_id, action, reconciliation_status, reconciliation_reason,
    parent_snapshot_before
)
SELECT l.id_lot, 'empty_parent_archived', 'review_required',
       'Parent had no building cycle; archived without inventing a building.',
       to_jsonb(l)
FROM public.lots_production l
WHERE NOT EXISTS (
    SELECT 1 FROM public.cycles_production c WHERE c.id_lot = l.id_lot
)
ON CONFLICT DO NOTHING;

DELETE FROM public.lots_production l
WHERE NOT EXISTS (
    SELECT 1 FROM public.cycles_production c WHERE c.id_lot = l.id_lot
)
AND EXISTS (
    SELECT 1 FROM public.independent_lot_migration_map m
    WHERE m.old_lot_id = l.id_lot AND m.action = 'empty_parent_archived'
);

-- Parentless cycles are repaired only from their own existing metadata. Shared
-- parent metadata stays authoritative where it exists, while flock count is
-- always the cycle's value, including NULL.
DO $split$
DECLARE
    source_row RECORD;
    new_lot_id INTEGER;
    effective_flock INTEGER;
    effective_name VARCHAR(100);
    effective_strain VARCHAR(100);
    effective_start DATE;
    effective_age INTEGER;
    effective_duration INTEGER;
    effective_planned_end DATE;
    effective_actual_end DATE;
    effective_status VARCHAR(30);
    effective_notes TEXT;
    effective_created TIMESTAMPTZ;
    effective_modified TIMESTAMPTZ;
    effective_creator INTEGER;
    effective_modifier INTEGER;
    review_reasons TEXT;
    migration_action VARCHAR(40);
BEGIN
    FOR source_row IN
        SELECT s.* FROM independent_lot_migration_source s
        WHERE NOT EXISTS (
            SELECT 1 FROM public.independent_lot_migration_map m
            WHERE m.id_cycle = s.id_cycle
        )
        ORDER BY s.id_cycle
    LOOP
        IF source_row.parent_id IS NOT NULL THEN
            effective_name := source_row.parent_nom_lot;
            effective_strain := source_row.parent_souche;
            effective_start := source_row.parent_date_debut;
            effective_age := source_row.parent_age_depart_semaines;
            effective_flock := source_row.cycle_effectif_initial;
            effective_duration := source_row.parent_duree_semaines;
            effective_planned_end := source_row.parent_date_fin_prevue;
            effective_actual_end := source_row.parent_date_fin_reelle;
            effective_status := source_row.parent_statut;
            effective_notes := source_row.parent_notes;
            effective_created := source_row.parent_date_creation;
            effective_modified := source_row.parent_date_modification;
            effective_creator := source_row.parent_user_creation;
            effective_modifier := source_row.parent_user_modification;
            migration_action := CASE WHEN source_row.child_count > 1
                THEN 'split_shared_parent' ELSE 'retained_single_parent' END;
        ELSE
            effective_name := source_row.nom_cycle;
            effective_strain := source_row.cycle_souche;
            effective_start := source_row.cycle_date_debut;
            effective_age := source_row.cycle_age_depart_semaines;
            effective_flock := source_row.cycle_effectif_initial;
            effective_duration := source_row.cycle_duree_semaines;
            effective_planned_end := source_row.cycle_date_fin_prevue;
            effective_actual_end := source_row.cycle_date_fin_reelle;
            effective_status := source_row.cycle_statut;
            effective_notes := source_row.cycle_notes;
            effective_created := source_row.cycle_date_creation;
            effective_modified := source_row.cycle_date_modification;
            effective_creator := source_row.cycle_user_creation;
            effective_modifier := source_row.cycle_user_modification;
            migration_action := CASE WHEN source_row.old_lot_id IS NULL
                THEN 'created_from_parentless_cycle' ELSE 'created_from_missing_parent' END;
        END IF;

        IF effective_name IS NULL OR effective_start IS NULL
           OR effective_duration IS NULL OR effective_planned_end IS NULL
           OR effective_status IS NULL THEN
            RAISE EXCEPTION 'Independent-lot migration blocked: required source metadata is missing for cycle %.',
                source_row.id_cycle;
        END IF;

        review_reasons := concat_ws(', ',
            CASE WHEN source_row.parent_id IS NULL
                THEN 'cycle had no valid parent; copied cycle metadata' END,
            CASE WHEN source_row.parent_id IS NOT NULL
                  AND source_row.cycle_effectif_initial IS DISTINCT FROM source_row.parent_effectif_initial
                THEN 'cycle and parent flock values differ' END,
            CASE WHEN source_row.parent_id IS NOT NULL AND source_row.child_count > 1
                  AND source_row.parent_effectif_initial IS NULL
                THEN 'shared parent total is unknown' END,
            CASE WHEN source_row.parent_id IS NOT NULL AND source_row.child_count > 1
                  AND NOT source_row.all_child_flocks_known
                THEN 'one or more cycle flock values are unknown' END,
            CASE WHEN source_row.parent_id IS NOT NULL AND source_row.child_count > 1
                  AND source_row.parent_effectif_initial IS NOT NULL
                  AND source_row.all_child_flocks_known
                  AND source_row.child_flock_total <> source_row.parent_effectif_initial
                THEN 'sum of cycle flock values differs from shared parent total' END,
            CASE WHEN source_row.parent_id IS NOT NULL AND (
                source_row.nom_cycle IS DISTINCT FROM source_row.parent_nom_lot
                OR source_row.cycle_souche IS DISTINCT FROM source_row.parent_souche
                OR source_row.cycle_date_debut IS DISTINCT FROM source_row.parent_date_debut
                OR source_row.cycle_age_depart_semaines IS DISTINCT FROM source_row.parent_age_depart_semaines
                OR source_row.cycle_duree_semaines IS DISTINCT FROM source_row.parent_duree_semaines
                OR source_row.cycle_date_fin_prevue IS DISTINCT FROM source_row.parent_date_fin_prevue
                OR source_row.cycle_date_fin_reelle IS DISTINCT FROM source_row.parent_date_fin_reelle
                OR source_row.cycle_statut IS DISTINCT FROM source_row.parent_statut
                OR source_row.cycle_notes IS DISTINCT FROM source_row.parent_notes
            ) THEN 'compatibility snapshot differed from authoritative parent' END
        );

        IF source_row.parent_id IS NOT NULL AND source_row.child_ordinal = 1 THEN
            new_lot_id := source_row.parent_id;
            UPDATE public.lots_production SET effectif_initial = effective_flock
            WHERE id_lot = new_lot_id;
        ELSE
            INSERT INTO public.lots_production (
                nom_lot, souche, date_debut, age_depart_semaines, effectif_initial,
                duree_semaines, date_fin_prevue, date_fin_reelle, statut, notes,
                date_creation, date_modification, id_utilisateur_creation, id_utilisateur_modification
            ) VALUES (
                effective_name, effective_strain, effective_start, effective_age,
                effective_flock, effective_duration, effective_planned_end,
                effective_actual_end, effective_status, effective_notes,
                effective_created, effective_modified, effective_creator, effective_modifier
            ) RETURNING id_lot INTO new_lot_id;
        END IF;

        INSERT INTO public.independent_lot_migration_map (
            old_lot_id, id_cycle, new_lot_id, action, reconciliation_status,
            reconciliation_reason, parent_snapshot_before, cycle_snapshot_before
        ) VALUES (
            source_row.old_lot_id, source_row.id_cycle, new_lot_id, migration_action,
            CASE WHEN NULLIF(review_reasons, '') IS NULL THEN 'pending' ELSE 'review_required' END,
            NULLIF(review_reasons, ''), source_row.parent_snapshot, source_row.cycle_snapshot
        ) ON CONFLICT DO NOTHING;

        UPDATE public.cycles_production SET
            id_lot = new_lot_id,
            nom_cycle = effective_name,
            souche = effective_strain,
            date_debut = effective_start,
            age_depart_semaines = effective_age,
            effectif_initial = effective_flock,
            duree_semaines = effective_duration,
            date_fin_prevue = effective_planned_end,
            date_fin_reelle = effective_actual_end,
            statut = effective_status,
            notes = effective_notes,
            id_utilisateur_modification = effective_modifier
        WHERE id_cycle = source_row.id_cycle;
    END LOOP;
END
$split$;

